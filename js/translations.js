function addTranslations(e) {
    if (!e || "object" != typeof e)
        return;
    const r = ["ru", "en", "es", "zh", "ar", "hi", "pt", "ja", "de", "fr", "uk", "tr"];
    for (const n of Object.keys(e)) {
        const a = e[n];
        if (a && "object" == typeof a)
            for (const lang of r) {
                const val = void 0 !== a[lang] ? a[lang] : a.en ?? a.ru;
                void 0 !== val && (translations[lang] || (translations[lang] = {}), translations[lang][n] = val)
            }
    }
}
